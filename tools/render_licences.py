"""Writes docs/licences.md from the LICENCES.toml table of every package that has one.

Each table row says what a dataset, model, voice or library is, the licence read at its
publisher, and the date it was read. `python tools/render_licences.py` rewrites the page;
`--check` exits 1 when it is out of date (tests/test_docs.py runs `render`).
"""

import argparse
import tomllib
from collections.abc import Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "licences.md"
SECTIONS = (
    ("packages/ml", "Image model: datasets and weights"),
    ("packages/voice", "Voice translation: models, voices, engines and libraries"),
    ("packages/pricing", "Pricing data"),
)
HEADER = """# Licences and attribution

Generated by `tools/render_licences.py` from the `LICENCES.toml` of each package; change a table
and run `make docs`, never this page. Every row carries the date its licence was read at the
publisher.

DentaBridge's own code is MIT ([LICENSE](../LICENSE)). Datasets are downloaded by the user and are
not redistributed here, and model weights are not stored in this repository. The Piper voice
engine is GPL-3.0: it runs as a separate process the code only talks to over HTTP, and it is
never imported.
"""
COLUMNS = ("Component", "Use", "Licence", "Status", "Source and notes")


def rows(package: str) -> list[dict[str, str]]:
    """The rows of a package's table, with the same keys whatever the table called its fields."""
    document: dict[str, Any] = tomllib.loads(
        (ROOT / package / "LICENCES.toml").read_text(encoding="utf-8")
    )
    found = []
    for table in document.values():
        for row in table:
            found.append(
                {
                    "component": str(row["component"]),
                    "use": str(row.get("role") or row.get("used") or row.get("kind") or ""),
                    "licence": str(row["licence"]),
                    "verified_on": str(row["verified_on"]),
                    "status": str(row["status"]),
                    "source": str(row.get("url") or row.get("origin") or ""),
                    "note": str(row.get("note") or ""),
                }
            )
    return found


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render() -> str:
    parts = [HEADER]
    for package, title in SECTIONS:
        parts += [f"\n## {title}\n", f"From `{package}/LICENCES.toml`.\n"]
        parts += ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
        for row in rows(package):
            where = row["source"] + (f" — {row['note']}" if row["note"] else "")
            cells = (
                row["component"],
                row["use"],
                f"{row['licence']}<br>read {row['verified_on']}",
                row["status"],
                where,
            )
            parts.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return "\n".join(parts) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    args = parser.parse_args(argv)
    rendered = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != rendered:
            print(f"{PAGE.relative_to(ROOT)} is out of date: run `make docs`")
            return 1
        return 0
    PAGE.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
